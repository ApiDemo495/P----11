def _raw() -> bool:
    return os.environ.get("MANDATE_RAW") == "1"


def cfg(symbol: str) -> dict | None:
    if _raw():
        return None
    return MANDATE.get(symbol)


def allows(symbol: str, tf: str) -> bool:
    """False → this (asset, tf) may not issue (tier is capped watch-only)."""
    c = cfg(symbol)
    if c is None:
        return True
    return tf in c["tfs"]


def mode(symbol: str) -> str | None:
    """Per-asset system mode override (None = follow the global setting)."""
    c = cfg(symbol)
    return c["mode"] if c else None


def new_rr(symbol: str) -> float | None:
    c = cfg(symbol)
    return c.get("new_rr") if c else None


def level_scale(symbol: str, tf: str) -> tuple[float, float] | None:
    """(k, R) for OLD-mode mandate cells; None = normal path."""
    c = cfg(symbol)
    if not c or tf not in c["tfs"]:
        return None
    return float(c["k"]), float(c["R"])


# ─────────────────────── tape features (hourly resample) ───────────────────────

_hourly_cache: dict = {"at": 0.0, "key": None, "val": None}


def hourly_bars(feed, symbol: str, max_age: float = 45.0):
    """(closes, highs, lows) resampled to hour buckets from the live tape.

    The mandate measured every tape feature on 1h bars; live feeds are
    minute bars, so features are computed on an hourly view to keep the
    semantics identical to the measurement. The partial current hour
    carries the latest minute's close/high/low."""
    try:
        st = feed.state(symbol)
        times = list(st.times)
        closes = list(st.closes)
        highs = list(st.highs or closes)
        lows = list(st.lows or closes)
    except Exception:
        return [], [], []
    if not times:
        return [], [], []
    key = (symbol, times[-1], len(times))
    now = time.time()
    if (_hourly_cache["key"] == key
            and now - _hourly_cache["at"] < max_age):
        return _hourly_cache["val"]
    cs: list[float] = []
    hs: list[float] = []
    ls: list[float] = []
    last_hour = None
    for t, c, h, l in zip(times, closes, highs, lows):
        hb = int(t) // 3600
        if hb != last_hour:
            cs.append(float(c))
            hs.append(float(h))
            ls.append(float(l))
            last_hour = hb
        else:
            cs[-1] = float(c)
            hs[-1] = max(hs[-1], float(h))
            ls[-1] = min(ls[-1], float(l))
    _hourly_cache.update(at=now, key=key, val=(cs, hs, ls))
    return cs, hs, ls


def hourly_closes(feed, symbol: str) -> list[float]:
    return hourly_bars(feed, symbol)[0]


def _rsi14(closes: list[float]) -> float:
    """RSI(14) with the walk's window (14 diffs of the last 15 closes).

    This is the variant backtest/mandate.direction_variants recorded
    for the ``rsi`` DIRECTION rule (≤30 → +1, ≥70 → −1)."""
    if len(closes) < 15:
        return 50.0
    g = l = 0.0
    for a, b in zip(closes[-15:-1], closes[-14:]):
        d = b - a
        if d >= 0:
            g += d
        else:
            l -= d
    if l <= 0:
        return 100.0
    return 100.0 - 100.0 / (1.0 + g / l)


def _rsi_filter(closes: list[float]) -> float:
    """RSI as backtest/mandate_search._features computed it for the
    ``rsi_ext`` issuance filter: diffs k = i−14 … i (15 diffs over the
    last 16 closes). Kept separate so the shipped filter is bit-exact
    with the number the search selected on."""
    if len(closes) < 16:
        return 50.0
    g = l = 0.0
    for k in range(len(closes) - 15, len(closes)):
        d = closes[k] - closes[k - 1]
        if d >= 0:
            g += d
        else:
            l -= d
    if l <= 0:
        return 100.0
    return 100.0 - 100.0 / (1.0 + g / max(l, 1e-12))


def _mom44(closes: list[float]) -> int:
    if len(closes) < 45:
        return 0
    d = closes[-1] - closes[-45]
    return 1 if d > 0 else (-1 if d < 0 else 0)


def _gate_ok(cs: list[float], hs: list[float], ls: list[float]) -> bool:
    """ATR14% top-tercile of its trailing 120 hourly bars.

    Exact replica of backtest/mandate_search._features: true TR
    (max(h−l, |h−prev_c|, |l−prev_c|)), ATR = mean(TR14)/close ×100,
    threshold = the 2/3 quantile of the trailing 120 values."""
    n = 14
    if len(cs) < n + 31:
        return True                    # too fresh to judge — don't block
    atr: list[float] = []
    for i in range(n, len(cs)):
        seg_tr = []
        for k in range(i - n + 1, i + 1):
            pc = cs[k - 1]
            if not pc:
                continue
            # true TR in PRICE units (max of h−l and both gaps to the
            # previous close) — the % division happens once, against
            # the current close, exactly like mandate._atr_pct
            seg_tr.append(max(hs[k] - ls[k], abs(hs[k] - pc),
                              abs(ls[k] - pc)))
        if seg_tr and cs[i]:
            atr.append(sum(seg_tr) / len(seg_tr) / cs[i] * 100)
    trail = atr[-120:]
    if len(trail) < 30:
        return True
    thr = sorted(trail)[int(len(trail) * (2 / 3))]
    return trail[-1] >= thr


def filter_ok(symbol: str, tf: str, feed) -> tuple[bool, str]:
    """Issuance filter for a mandate cell → (pass?, reason-if-blocked)."""
    c = cfg(symbol)
    if not c or tf not in c["tfs"]:
        return True, ""
    name = c.get("filter") or "none"
    if name == "none":
        return True, ""
    cs, hs, ls = hourly_bars(feed, symbol)
    if len(cs) < 45:
        return True, ""                # cold tape — never block on data
    if name in ("gate", "atr_top"):
        ok = _gate_ok(cs, hs, ls)
        return ok, ("" if ok else
                    "mandate filter: ATR% below top tercile (quiet tape)")
    if name == "rsi_ext":
        r = _rsi_filter(cs)
        ok = r <= 35.0 or r >= 65.0
        return ok, ("" if ok else
                    f"mandate filter: hourly RSI {r:.0f} not extreme (≤35/≥65)")
    if name == "momentum":
        ok = _mom44(cs) != 0
        return ok, ("" if ok else "mandate filter: no 44h momentum")
    return True, ""


# ─────────────────────── direction rules ───────────────────────

def apply_direction(symbol: str, tf: str, raw: int, tf4_raw: int,
                    feed) -> int:
    """Apply this cell's direction rule to the ladder's raw side.

    ``raw`` is the ladder output for THIS tf, ``tf4_raw`` the same
    pass's TF4 raw side (inv4g). Tape rules read the hourly resample."""
    c = cfg(symbol)
    if not c or tf not in c["tfs"]:
        return raw
    rule = c.get("direction") or "base"
    if rule == "base":
        return raw
    if rule == "fade":
        return -raw
    if rule == "inv4g":
        return -tf4_raw if tf4_raw else raw
    closes = hourly_closes(feed, symbol)
    if rule == "mom44":
        m = _mom44(closes)
        return m if m else raw
    if rule == "antimom44":
        m = _mom44(closes)
        return -m if m else raw
    if rule == "rsi":
        r = _rsi14(closes)
        if r <= 30.0:
            return 1
        if r >= 70.0:
            return -1
        return raw
    return raw


def direction_rule(symbol: str, tf: str) -> str:
    c = cfg(symbol)
    if not c or tf not in c["tfs"]:
        return "base"
    return c.get("direction") or "base"
