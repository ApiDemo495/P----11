"""Per-asset mandate configuration — measured on 2y of REAL market data.

Generated by ``backtest/mandate_search.py`` over the mandate walk's
43k recorded trades (Binance Vision 1h, 2024-11 → 2026-09, zero gaps).
Each asset's config is the single construction that

  * is POSITIVE in ≥5 of 6 temporal folds of the 2y sample, and
  * reaches full-sample EV ≥ +0.070 R after friction,

with the search run over direction rules × TF subsets × barriers ×
filters (9,000 candidates per asset). These are IN-SAMPLE measurements
with a stability constraint — a description of the past, not a promise
about the future; forward results must be monitored (the honest frame
is ``backtest/REAL_RESULTS.md`` §9-10).

Semantics wired into the engine (app/engine.py):

  * ``tfs``      — TFs this asset may ISSUE on; others are watch-only
                   (removes the measured-useless horizons).
  * ``direction``— rule applied to the ladder's raw side:
                     base/fade    raw or its inverse
                     inv4g        inverse of this pass's TF4 raw side
                     mom44        sign of the 44-HOUR momentum
                     antimom44    its inverse
                     rsi          RSI(14) extreme override else raw
                   (tape features are computed on an HOURLY resample
                   of the feed so live semantics match the 1h-bar
                   measurement exactly).
  * ``mode``      — per-asset system mode (overrides the global
                   old/new selector for this asset).
  * ``k``, ``R``  — barrier geometry on the measured q80-MAE stop:
                   sl ×= k, tp = sl × R (OLD mode). Mandate cells use
                   the searched raw geometry — the generic asset
                   profile / TF envelope are skipped for them.
  * ``new_rr``    — NEW-mode target multiple of the stop.
  * ``filter``    — issuance filter (also enforced in _tier_for):
                     gate     ATR% top-tercile of its trailing 120h
                     rsi_ext  hourly RSI(14) ≤35 or ≥65
                     momentum sign(44h momentum) exists
                     atr_top  same as gate (alias)
                     none     no filter

``MANDATE_RAW=1`` (set by backtest/mandate.py) disables all of this so
the research walk keeps measuring the RAW engine the rules are defined
against.
"""
